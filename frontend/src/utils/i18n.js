/**
 * Helper hook / getter for translations
 */
export function getTranslation(lang = 'hi') {
  return TRANSLATIONS[lang] || TRANSLATIONS.hi;
}

/**
 * Helper to speak text aloud in the current language's IETF code
 */
export function speakInLanguage(text, lang = 'hi') {
  if (!('speechSynthesis' in window)) return;
  window.speechSynthesis.cancel();
  const langObj = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = langObj.voiceCode || 'hi-IN';
  utterance.rate = 0.92;
  window.speechSynthesis.speak(utterance);
}
